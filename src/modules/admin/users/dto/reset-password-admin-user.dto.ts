import { ApiPropertyOptional } from '@nestjs/swagger';
import { IsOptional, IsString, MinLength } from 'class-validator';

export class ResetPasswordAdminUserDto {
  @ApiPropertyOptional({
    description:
      'Specific new password (min 8 chars). If omitted, an unpredictable secure password is generated automatically',
    example: 'AutoGenerated@2026',
    type: 'string',
  })
  @IsOptional()
  @IsString()
  @MinLength(8)
  newPassword?: string;
}
